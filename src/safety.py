"""Pose-dependent contact-velocity limit for the free-floating arm. Owner: P4.

Written by P3 so the safety case is complete end to end; P4 owns the numbers, the hazard
table and the verification matrix (docs/SAFETY.md, generated by `python -m src.verify`).

Plan v2, Section 3:
    Operational-space inertia   Lambda(q) = (J M^-1 J^T)^-1      (full floating M, 13 DOF)
    Effective mass along u      m_eff = 1 / (u^T Lambda_v^-1 u)  (point contact: linear rows)
    Contact impulse             J_imp = (1 + e) mu v
    Unrestrained human          dv_h  = J_imp / m_h
    Permissible velocity        v_max(q) = limit / ((1 + e) m_eff(q))

Contact model: ISO/TS 15066:2016 Annex A (Tables A.2, A.3), the two-body energy model
    E = F^2 / (2 k) = 1/2 mu v^2   ->   v_max = F / sqrt(mu k)
  * free (transient) contact: the body region can recoil. F = 2 x the quasi-static limit
    (Table A.2 multiplier), mu = reduced mass of m_eff and the region's m_H (Table A.3).
  * clamped contact: the body is pinned against structure and cannot recoil (an EVA
    astronaut in a foot restraint, or against the target spacecraft). ISO treats this as
    quasi-static contact: F = the quasi-static limit and mu = m_eff (all the robot's kinetic
    energy goes into the body spring). Conservative choice by P3 -- P4 to confirm.
  * Skull/forehead and face: transient contact is "not applicable" in ISO -- no contact is
    acceptable, so they are not in the table; the arm must never be driven at the head.
ISO 10218-1:2025 excludes space robots; we borrow the body model only (plan, contribution 3).

What gives way at impact on our side:
    locked=True   joints held stiff by the servos, only the 6 base DOFs move (conservative,
                  the default); locked=False  every joint back-drivable (lower bound).

    python -m src.safety --model medium                         # numbers at the home pose
    python -m src.safety --map --out data/safety/vmax_medium.csv
    python -m src.safety --montecarlo --out data/safety/montecarlo.csv
"""
import argparse

import mujoco
import numpy as np

from src.dynamics import EE_SITE, kin, mass_matrix, site_jacobian

# ISO/TS 15066:2016 Annex A. F_qs: maximum permissible quasi-static force [N] (Table A.2,
# the body-region value), transient multiplier 2 for every region below; k: effective
# spring constant [N/m] (Table A.3, N/mm x 1e3); m: effective body mass [kg] (Table A.3).
BODY = {
    "neck":            dict(F_qs=150.0, k=50e3, m=1.2),
    "back_shoulders":  dict(F_qs=210.0, k=35e3, m=40.0),
    "chest":           dict(F_qs=140.0, k=25e3, m=40.0),
    "abdomen":         dict(F_qs=110.0, k=10e3, m=40.0),
    "pelvis":          dict(F_qs=180.0, k=25e3, m=40.0),
    "upper_arm":       dict(F_qs=150.0, k=30e3, m=3.0),
    "lower_arm":       dict(F_qs=160.0, k=40e3, m=2.0),
    "hand":            dict(F_qs=140.0, k=75e3, m=0.6),
    "thigh":           dict(F_qs=220.0, k=50e3, m=75.0),
    "lower_leg":       dict(F_qs=130.0, k=60e3, m=75.0),
}
TRANSIENT_MULT = 2.0
RESTRAINTS = ("free", "clamped")
RESTITUTION = 0.0       # e: plastic impact (soft tissue). P4 to justify.

# Design case for the runtime limiter and the HUD: the most restrictive body region AND
# restraint (free or clamped), with m_design (below). Joints-locked m_eff is reported as the
# rigid upper bound only: the +/-5 Nm servos give way in an impact (impact campaign).
DESIGN_RESTRAINT = None    # None = the worse of free and clamped
GOVERNOR_MARGIN = 0.85     # the limiter keeps the hand at <= 85 % of the design v_max


# --- mass properties -------------------------------------------------------------------

def op_space_inertia(model, data, locked=True, site=EE_SITE):
    """6 x 6 Lambda(q) at the hand, world frame, rows [linear; angular]."""
    M, J = mass_matrix(model, data), site_jacobian(model, data, site)
    n = 6 if locked else model.nv
    return np.linalg.inv(J[:, :n] @ np.linalg.solve(M[:n, :n], J[:, :n].T))


def m_eff(model, data, u=None, locked=True, site=EE_SITE):
    """Effective mass [kg] at the hand along unit direction u (world). Default u: tool axis."""
    M, J = mass_matrix(model, data), site_jacobian(model, data, site)[:3]
    if u is None:
        u = data.site_xmat[model.site(site).id].reshape(3, 3)[:, 0]   # tool axis = link7 x
    u = np.asarray(u, float) / np.linalg.norm(u)
    n = 6 if locked else model.nv
    return float(1.0 / (u @ J[:, :n] @ np.linalg.solve(M[:n, :n], J[:, :n].T) @ u))


def m_eff_worst(model, data, locked=False, site=EE_SITE):
    """(largest effective mass over all contact directions [kg], that direction): the top
    eigenpair of the linear operational-space inertia."""
    M, J = mass_matrix(model, data), site_jacobian(model, data, site)[:3]
    n = 6 if locked else model.nv
    w, V = np.linalg.eigh(J[:, :n] @ np.linalg.solve(M[:n, :n], J[:, :n].T))
    return float(1.0 / w[0]), V[:, 0]


def set_payload(model, mass, site=EE_SITE):
    """Attach a point payload [kg] at the tool point by changing link7's mass and centre of
    mass (its rotational inertia is left alone -- a point mass, fine for m_eff along a
    linear direction). Returns a function that undoes it."""
    b = model.site_bodyid[model.site(site).id]
    m0, c0 = float(model.body_mass[b]), model.body_ipos[b].copy()
    tip = model.site_pos[model.site(site).id]
    model.body_mass[b] = m0 + mass
    model.body_ipos[b] = (m0 * c0 + mass * tip) / (m0 + mass)

    def undo():
        model.body_mass[b], model.body_ipos[b] = m0, c0
    return undo


# --- limits ----------------------------------------------------------------------------

def reduced_mass(meff, m_other=None):
    return meff if m_other is None else 1.0 / (1.0 / meff + 1.0 / m_other)


def v_max_iso(meff, region="chest", restraint="free"):
    """ISO/TS 15066 energy model. free: transient limit, two-body mu. clamped: quasi-static
    limit, mu = m_eff (the body cannot recoil). Accepts arrays for meff."""
    b = BODY[region]
    if restraint == "free":
        return b["F_qs"] * TRANSIENT_MULT / np.sqrt(reduced_mass(np.asarray(meff, float), b["m"]) * b["k"])
    if restraint == "clamped":
        return b["F_qs"] / np.sqrt(np.asarray(meff, float) * b["k"])
    raise ValueError(f"restraint must be one of {RESTRAINTS}")


def v_max_design(meff, restraint=DESIGN_RESTRAINT):
    """(v_max, "region/restraint"): the most restrictive body region (and restraint, if None)."""
    rs = RESTRAINTS if restraint is None else (restraint,)
    vs = {f"{b}/{r}": float(v_max_iso(meff, b, r)) for b in BODY for r in rs}
    case = min(vs, key=vs.get)
    return vs[case], case


def impulse(meff, v, e=RESTITUTION, m_other=None):
    """Contact impulse [N s] for an approach speed v [m/s]."""
    return (1.0 + e) * reduced_mass(meff, m_other) * v


def delta_v_struck(meff, v, m_other, e=RESTITUTION):
    """Speed [m/s] given to an unrestrained body of mass m_other (plan: dv_h = J_imp / m_h)."""
    return impulse(meff, v, e, m_other) / m_other


def v_max_impulse(meff, limit, e=RESTITUTION, m_other=None):
    """Plan form: the speed whose contact impulse equals `limit` [N s]."""
    return limit / ((1.0 + e) * reduced_mass(meff, m_other))


def hardware_speed(Jstar_lin, u, qd_max=1.0):
    """Fastest the hand can move along u with every joint at most qd_max (the ctrlrange):
    max u.J* qd over the box = qd_max * sum_i |u . J*_i|."""
    return float(qd_max * np.abs(np.asarray(u) @ Jstar_lin).sum())


# --- runtime --------------------------------------------------------------------------

def hand_speed_margin(model, data, locked=True, site=EE_SITE):
    """(hand speed, v_max along the direction of travel, region) for the HUD."""
    J = site_jacobian(model, data, site)[:3]
    v = J @ data.qvel
    speed = float(np.linalg.norm(v))
    u = v / speed if speed > 1e-6 else None
    vmax, region = v_max_design(m_design(model, data, u, site))
    return speed, vmax, region


class SpeedGovernor:
    """Safety function (H2 / R2): scale the commanded joint rates so the predicted hand speed
    J* qd stays <= GOVERNOR_MARGIN x v_max(q) along its own direction (design case). Keeps
    the direction, like the ctrlrange limit. Returns (qd, scale) -- scale < 1 means it acted."""

    def __init__(self, margin=GOVERNOR_MARGIN, restraint=DESIGN_RESTRAINT):
        self.margin, self.restraint = margin, restraint
        self._scratch = None
        self.last_vmax = float("nan")   # design v_max along the commanded direction, last call (logged)

    def __call__(self, model, data, qd):
        if self._scratch is None or self._scratch[0] is not model:
            self._scratch = (model, mujoco.MjData(model))
        s = self._scratch[1]
        s.qpos[:] = data.qpos
        mujoco.mj_forward(model, s)
        v = kin(model, s).Jstar[:3] @ qd
        speed = float(np.linalg.norm(v))
        if speed < 1e-6:
            self.last_vmax = float("nan")
            return qd, 1.0
        self.last_vmax = v_max_design(m_design(model, s, v / speed), self.restraint)[0]
        lim = self.margin * self.last_vmax
        if speed <= lim:
            return qd, 1.0
        return qd * (lim / speed), lim / speed


# --- maps and the Monte Carlo sweep ------------------------------------------------------

def vmax_map(model, n=41, region=None, restraint=DESIGN_RESTRAINT, locked=False, q_base=None, direction="worst"):
    """v_max over shoulder pitch (j2) x elbow (j4), other joints at the home pose; contact
    in the worst direction at that pose (direction="tool": along the tool axis), m_design
    (locked=True: rigid-joint mass instead). region None =
    design case (most restrictive region and restraint). Returns
    (q2, q4, V) with V[i4, i2]; NaN where the arm is in collision with the base."""
    d = mujoco.MjData(model)
    q_home = model.key("home").qpos.copy() if q_base is None else np.asarray(q_base, float)
    lo, hi = model.jnt_range[2], model.jnt_range[4]
    q2, q4 = np.linspace(lo[0], lo[1], n), np.linspace(hi[0], hi[1], n)
    V = np.full((n, n), np.nan)
    for a, s in enumerate(q2):
        for b, e in enumerate(q4):
            d.qpos[:] = q_home
            d.qpos[8], d.qpos[10] = s, e
            mujoco.mj_forward(model, d)
            if d.ncon:
                continue
            if direction == "worst":
                me = m_eff_worst(model, d, locked)[0] + (0.0 if locked else SERVO_MASS)
            else:
                me = m_eff(model, d, locked=True) if locked else m_design(model, d)
            V[b, a] = v_max_design(me, restraint)[0] if region is None else v_max_iso(me, region, restraint)
    return q2, q4, V


def random_pose(model, data, rng, tries=200):
    """A collision-free arm pose drawn uniformly inside the joint limits, base at home."""
    lim = model.jnt_range[1:]
    for _ in range(tries):
        data.qpos[:] = model.key("home").qpos
        data.qpos[7:] = rng.uniform(lim[:, 0], lim[:, 1])
        mujoco.mj_forward(model, data)
        if data.ncon == 0:
            return True
    return False


def montecarlo(sizes=("small", "medium", "large"), payloads=(0.0, 2.5, 5.0), n=300, seed=0,
               v_cap=None):
    """Plan W7-recess (P4): pose x velocity x payload x restraint x servicer size.

    For each servicer and payload, n random collision-free poses, each with a random contact
    direction u and a random approach speed v ~ U(0, hardware max along u). Returns a list of
    dict rows (one per pose) with m_eff (locked / free), the hardware speed, the sampled
    speed and, per restraint, the design-case v_max and its region. v_cap: the teleop's
    largest commanded hand speed (default from src.teleop / src.schemes)."""
    from pathlib import Path
    root = Path(__file__).resolve().parent.parent
    if v_cap is None:
        v_cap = teleop_speed_cap()
    rng = np.random.default_rng(seed)
    rows = []
    for size in sizes:
        model = mujoco.MjModel.from_xml_path(str(root / "models" / f"ff_{size}.xml"))
        d = mujoco.MjData(model)
        for payload in payloads:
            undo = set_payload(model, payload)
            for i in range(n):
                if not random_pose(model, d, rng):
                    continue
                u = rng.normal(size=3)
                u /= np.linalg.norm(u)
                k = kin(model, d)
                v_hw = hardware_speed(k.Jstar[:3], u)
                row = dict(size=size, payload_kg=payload, sample=i,
                           m_eff_locked=m_eff(model, d, u, True), m_eff_free=m_eff(model, d, u, False),
                           v_hw=v_hw, v_sampled=float(rng.uniform(0, v_hw)), v_cap=v_cap,
                           sigma_min=float(np.linalg.svd(k.Jstar[:3], compute_uv=False)[-1]))
                row["m_design"] = m_design(model, d, u)
                row["axial"] = axial_alignment(model, d, u)
                for r in RESTRAINTS:
                    row[f"v_max_{r}"], row[f"region_{r}"] = v_max_design(row["m_design"], r)
                    row[f"v_max_{r}_locked"] = v_max_design(row["m_eff_locked"], r)[0]
                rows.append(row)
            undo()
    return rows


def summarize(rows):
    """Per size x payload x restraint: worst v_max and the share of samples where the
    hardware, the sampled speed or the teleop cap would exceed it."""
    import pandas as pd
    df = pd.DataFrame(rows)
    out = []
    for (size, payload), g in df.groupby(["size", "payload_kg"], sort=False):
        for r in RESTRAINTS:
            vm = g[f"v_max_{r}"]
            out.append(dict(size=size, payload_kg=payload, restraint=r, n=len(g),
                            m_design_median=g["m_design"].median(),
                            v_max_min=vm.min(), v_max_median=vm.median(),
                            worst_region=g.loc[vm.idxmin(), f"region_{r}"],
                            p_hw_exceeds=(g["v_hw"] > vm).mean(),
                            p_sampled_exceeds=(g["v_sampled"] > vm).mean(),
                            p_cap_exceeds=(g["v_cap"] > vm).mean(),
                            p_cap_exceeds_if_rigid=(g["v_cap"] > g[f"v_max_{r}_locked"]).mean()))
    return pd.DataFrame(out)


# --- simulated impact: which effective mass does the real arm present? ------------------
#
# The joints are velocity servos that saturate at +/-5 Nm, so in a hard impact they give way:
# the hand is neither "joints locked" (whole spacecraft behind it) nor "joints free". The
# campaign below drives the arm into an ISO body region (plate on a tissue spring, backed by
# the region mass or by the world) at random poses / directions, measures the peak force and
# turns it into an equivalent robot mass m_R. Measured (216 impacts, 3 servicers, 0 / 5 kg
# payload, 3 body cases): m_R is roughly m_eff(free) plus a few kg the servos transmit during
# the impact, nearly independent of the base mass (20 vs 1500 kg give the same peak force).
# m_design = m_eff(free) + SERVO_MASS is conservative for 215 / 216 impacts, the worst miss
# 15 % optimistic; GOVERNOR_MARGIN 0.85 covers all of them (checked by `python -m src.verify`).

SERVO_MASS = 6.0   # kg, from data/safety/impact.csv (DECISIONS 2026-10-14)


AXIAL_POWER = 2.0  # how fast the rigid mass takes over as the push lines up with the arm (impact fit)
AXIAL_SCALE = 0.02 # share of the rigid-joint mass reached when the push is exactly along the arm (impact fit:
                   # 0 already passes the direct force check, worst 0.96 of the ISO limit; 0.02 gives 0.90)


def axial_alignment(model, data, u, site=EE_SITE):
    """|cos| between the contact direction u and the shoulder (j2) -> tool line. Near 1 the push
    runs along the arm: the joints have no lever arm, cannot give way, and the impact is carried
    structurally into the spacecraft."""
    a = data.site_xpos[model.site(site).id] - data.xpos[model.body("link2").id]
    u = np.asarray(u, float)
    return float(abs(a @ u) / (np.linalg.norm(a) * np.linalg.norm(u)))


def m_design(model, data, u=None, site=EE_SITE):
    """Effective mass [kg] for the safety limit. Across the arm the servos give way: limp arm +
    SERVO_MASS. Along the arm they cannot: blend toward the rigid-joint mass with weight
    axial^AXIAL_POWER (fitted on data/safety/impact.csv, Kinova Gen3 geometry)."""
    if u is None:
        u = data.site_xmat[model.site(site).id].reshape(3, 3)[:, 0]
    soft = m_eff(model, data, u, locked=False, site=site) + SERVO_MASS
    w = AXIAL_SCALE * axial_alignment(model, data, u, site) ** AXIAL_POWER
    return soft + w * max(0.0, m_eff(model, data, u, locked=True, site=site) - soft)


def impact_limit(region, restraint):
    """The ISO force limit that applies: transient (2 x quasi-static) when free, quasi-static when clamped."""
    return BODY[region]["F_qs"] * (TRANSIENT_MULT if restraint == "free" else 1.0)


def impact_model(size, region, restraint, qpos=None, u=None, payload=0.0, gap=0.01):
    """The servicer posed at qpos (default home) plus an ISO body region a gap ahead of the hand
    along u (default tool axis): a plate on a spring of stiffness k (the tissue), backed by the
    region mass m_H on a frictionless slide (free) or by the world (clamped).
    Returns (model, qpos0) or (None, None) if the plate would start inside the arm."""
    from pathlib import Path
    from scipy.spatial.transform import Rotation
    root = Path(__file__).resolve().parent.parent
    spec = mujoco.MjSpec.from_file(str(root / "models" / f"ff_{size}.xml"))
    m0 = spec.compile()
    d0 = mujoco.MjData(m0)
    q0 = m0.key("home").qpos.copy() if qpos is None else np.asarray(qpos, float).copy()
    d0.qpos[:] = q0
    mujoco.mj_forward(m0, d0)
    sid = m0.site(EE_SITE).id
    tip = d0.site_xpos[sid].copy()
    if u is None:
        u = d0.site_xmat[sid].reshape(3, 3)[:, 0]
    u = np.asarray(u, float) / np.linalg.norm(u)
    b = BODY[region]
    quat = Rotation.align_vectors([u], [[1.0, 0, 0]])[0].as_quat(scalar_first=True)
    b7 = m0.site_bodyid[sid]                     # tool link: start the plate clear of its capsule
    r_tool = max(float(m0.geom_size[g, 0]) for g in range(m0.ngeom)
                 if m0.geom_bodyid[g] == b7 and m0.geom_contype[g])
    hb = spec.worldbody.add_body(name="human", pos=tip + (r_tool + gap + 0.005) * u, quat=quat)
    extra = 1
    if restraint == "free":
        hb.add_joint(name="human_x", type=mujoco.mjtJoint.mjJNT_SLIDE, axis=[1, 0, 0],
                     limited=False, damping=0, armature=0)
        extra = 2
    hb.add_geom(type=mujoco.mjtGeom.mjGEOM_SPHERE, size=[0.01, 0, 0], mass=b["m"], contype=0, conaffinity=0)
    pb = hb.add_body(name="plate")
    m_plate = 0.05
    pb.add_joint(name="tissue", type=mujoco.mjtJoint.mjJNT_SLIDE, axis=[1, 0, 0], limited=False,
                 stiffness=b["k"], damping=0.2 * 2 * np.sqrt(b["k"] * m_plate), armature=0)
    pb.add_geom(type=mujoco.mjtGeom.mjGEOM_BOX, size=[0.005, 0.05, 0.05], mass=m_plate,
                priority=1, solref=[0.001, 1], contype=1, conaffinity=1)
    for key in spec.keys:
        key.qpos = list(q0) + [0.0] * extra
    model = spec.compile()
    if payload:
        set_payload(model, payload)
    d = mujoco.MjData(model)
    mujoco.mj_resetDataKeyframe(model, d, model.key("home").id)
    mujoco.mj_forward(model, d)
    if d.ncon:
        return None, None
    return model, model.key("home").qpos.copy()


def impact_test(size, region, restraint, qpos=None, u=None, v=0.05, payload=0.0, t_after=0.25):
    """Drive the hand at v [m/s] along u into the body region, the operator still pushing
    (worst case); the joints are the real servos (kv 20, +/-5 Nm), the base floats.
    Returns dict(F_peak [N], v_contact [m/s], m_R_eq [kg]) or None if it never touched."""
    m, q0 = impact_model(size, region, restraint, qpos, u, payload)
    if m is None:
        return None
    d = mujoco.MjData(m)
    d.qpos[:] = q0
    mujoco.mj_forward(m, d)
    sid, jt = m.site(EE_SITE).id, m.joint("tissue").qposadr[0]
    if u is None:
        u = d.site_xmat[sid].reshape(3, 3)[:, 0]
    u = np.asarray(u, float) / np.linalg.norm(u)
    n_sub, peak, t_hit, v_hit = round(0.01 / m.opt.timestep), 0.0, None, 0.0
    k = BODY[region]["k"]
    while d.time < 1.5 and (t_hit is None or d.time < t_hit + t_after):
        M = mass_matrix(m, d)
        J = site_jacobian(m, d)
        Js = (J[:, 6:13] - J[:, :6] @ np.linalg.solve(M[:6, :6], M[:6, 6:13]))[:3]
        qd = Js.T @ np.linalg.solve(Js @ Js.T + 1e-4 * np.eye(3), v * u)
        d.ctrl[:] = qd / max(1.0, np.abs(qd).max())
        for _ in range(n_sub):
            mujoco.mj_step(m, d)
            f = k * d.qpos[jt]
            if t_hit is None and f > 1e-3:
                t_hit, v_hit = d.time, float((site_jacobian(m, d)[:3] @ d.qvel) @ u)
            peak = max(peak, f)
    if t_hit is None or v_hit < 0.2 * v:
        return None
    Z = peak / v_hit                       # N per m/s: sqrt(mu k) in the energy model
    mu = Z * Z / k
    m_H = BODY[region]["m"]
    m_R = mu if restraint == "clamped" else (mu * m_H / (m_H - mu) if mu < m_H else np.inf)
    return dict(F_peak=peak, v_contact=v_hit, m_R_eq=m_R)


def _impact_one(args):
    size, region, restraint, payload, seed = args
    rng = np.random.default_rng(seed)
    from pathlib import Path
    root = Path(__file__).resolve().parent.parent
    model = mujoco.MjModel.from_xml_path(str(root / "models" / f"ff_{size}.xml"))
    if payload:
        set_payload(model, payload)
    d = mujoco.MjData(model)
    for _ in range(20):
        if not random_pose(model, d, rng):
            continue
        u = rng.normal(size=3)
        u /= np.linalg.norm(u)
        r = impact_test(size, region, restraint, d.qpos.copy(), u, payload=payload)
        if r is None:
            continue
        q = d.qpos.copy()
        mujoco.mj_forward(model, d)
        md = m_design(model, d, u)
        v_gov = GOVERNOR_MARGIN * float(v_max_iso(md, region, restraint))
        # direct check: hit again at the speed the limiter allows, compare the real peak force
        g = impact_test(size, region, restraint, q, u, v=v_gov, payload=payload)
        return dict(size=size, region=region, restraint=restraint, payload_kg=payload, seed=seed,
                    m_eff_free=m_eff(model, d, u, False), m_eff_locked=m_eff(model, d, u, True),
                    axial=axial_alignment(model, d, u), m_design=md, v_gov=v_gov,
                    F_at_gov=g["F_peak"] if g else np.nan, F_limit=impact_limit(region, restraint), **r)
    return None


def impact_campaign(n=12, sizes=("small", "medium", "large"), payloads=(0.0, 5.0),
                    cases=(("lower_leg", "free"), ("chest", "free"), ("hand", "clamped")), procs=8):
    """Random-pose / random-direction impacts; rows with the measured and predicted masses."""
    from multiprocessing import Pool
    jobs = [(s, r, c, p, 1000 * i + 7) for s in sizes for (r, c) in cases for p in payloads for i in range(n)]
    with Pool(procs) as pl:
        rows = [r for r in pl.map(_impact_one, jobs) if r is not None]
    for r in rows:
        r["v_max_sim"] = impact_limit(r["region"], r["restraint"]) / (r["F_peak"] / r["v_contact"])
        r["v_max_design"] = float(v_max_iso(r["m_eff_free"] + SERVO_MASS, r["region"], r["restraint"]))
        r["v_max_locked"] = float(v_max_iso(r["m_eff_locked"], r["region"], r["restraint"]))
    return rows

def teleop_speed_cap():
    """Largest hand speed the teleop can command: full stick plus the saturated pose pull."""
    from src.schemes import K_POSE, POS_CLIP
    from src.teleop import LIN_SPEED
    return LIN_SPEED + K_POSE * POS_CLIP


def main():
    from pathlib import Path
    ap = argparse.ArgumentParser(description="Contact-velocity limit (P4)")
    ap.add_argument("--model", choices=["small", "medium", "large"], default="medium")
    ap.add_argument("--map", action="store_true", help="v_max heatmap over shoulder x elbow")
    ap.add_argument("--montecarlo", action="store_true", help="pose x speed x payload x restraint x size")
    ap.add_argument("--impact", action="store_true", help="simulated impacts at random poses (calibrates SERVO_MASS)")
    ap.add_argument("--rigid", action="store_true", help="map with rigid (locked) joints instead of the real servos")
    ap.add_argument("--direction", choices=["tool", "worst"], default="tool",
                    help="map contact direction: tool approach axis (Fig. 5) or the worst direction per pose")
    ap.add_argument("--n", type=int, help="map grid size (41) / Monte Carlo poses per cell (300)")
    ap.add_argument("--out", help="CSV for the map or the Monte Carlo")
    a = ap.parse_args()
    root = Path(__file__).resolve().parent.parent
    model = mujoco.MjModel.from_xml_path(str(root / "models" / f"ff_{a.model}.xml"))
    d = mujoco.MjData(model)
    mujoco.mj_resetDataKeyframe(model, d, model.key("home").id)
    mujoco.mj_forward(model, d)
    for label, me in (("rigid joints (upper bound)", m_eff(model, d, locked=True)),
                      ("limp joints (lower bound) ", m_eff(model, d, locked=False)),
                      ("design (limp + servo mass)", m_design(model, d))):
        vf, rf = v_max_design(me, "free")
        vc, rc = v_max_design(me, "clamped")
        print(f"home, {label}: m_eff {me:8.2f} kg   v_max free {vf:.3f} m/s ({rf})   clamped {vc:.3f} m/s ({rc})")
    print(f"teleop speed cap {teleop_speed_cap():.3f} m/s")
    if a.map:
        q2, q4, V = vmax_map(model, a.n or 41, locked=a.rigid, direction=a.direction)
        print(f"map: v_max {np.nanmin(V):.3f} .. {np.nanmax(V):.3f} m/s, {np.isnan(V).sum()} poses in collision")
        if a.out:
            out = Path(a.out)
            out.parent.mkdir(parents=True, exist_ok=True)
            np.savetxt(out, V, delimiter=",",
                       header=f"design-case v_max [m/s]; rows j4 {q4[0]:.3f}..{q4[-1]:.3f} rad, "
                              f"cols j2 {q2[0]:.3f}..{q2[-1]:.3f} rad, {len(q2)} each; NaN = collision")
            print("saved", out)
    if a.impact:
        import pandas as pd
        df = pd.DataFrame(impact_campaign(n=a.n or 12))
        df["delta"] = df.m_R_eq - df.m_eff_free
        ok = (GOVERNOR_MARGIN * df.v_max_design <= df.v_max_sim).mean()
        print(f"{len(df)} impacts; m_R - m_free max {df.delta.max():.2f} kg; design/sim max "
              f"{(df.v_max_design / df.v_max_sim).max():.3f}; governor conservative in {100 * ok:.1f} %")
        if a.out:
            df.to_csv(a.out, index=False)
            print("saved", a.out)
    if a.montecarlo:
        import pandas as pd
        rows = montecarlo(n=a.n or 300)
        s = summarize(rows)
        with pd.option_context("display.width", 200, "display.max_columns", 20):
            print(s.round(3).to_string(index=False))
        if a.out:
            out = Path(a.out)
            out.parent.mkdir(parents=True, exist_ok=True)
            pd.DataFrame(rows).to_csv(out, index=False)
            s.to_csv(out.with_name(out.stem + "_summary.csv"), index=False)
            print("saved", out, "and", out.with_name(out.stem + "_summary.csv"))


if __name__ == "__main__":
    main()
